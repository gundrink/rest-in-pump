import type { MarketSnapshot } from "@/lib/types";

/**
 * Fictional coins. If a real ticker ever matches, that is a spooky coincidence.
 * Every row is EXAMPLE data and is labelled that way in the UI.
 */
function example(
  partial: Pick<
    MarketSnapshot,
    "id" | "name" | "ticker" | "bornAt" | "diedAt" | "athUsd" | "priceUsd" | "volume24hUsd" | "lowVolumeDays"
  >,
): MarketSnapshot {
  return {
    mint: `example:${partial.id}`,
    athKind: "recorded",
    held: false,
    bagStatus: "unknown",
    isExample: true,
    chartUrl: null,
    ...partial,
  };
}

